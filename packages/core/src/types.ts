// @skervik/core — foundational domain types (M0 skeleton, S0.5.1).
//
// These are the minimal, real shapes behind the engine contract from tech
// spec §4.1 (`reduce`/`validate` themselves land in S0.5.2). Per ADR-0003
// every type here is plain data — no class instances, no functions, no
// `Map`/`Set` — so `GameState` can be event-sourced and deep-compared via
// JSON. M1 Classic rules extend these shapes; this file does not invent a
// full ruleset.

import type { EdgeId, TileId, VertexId } from './board.js';
import type { RuleProfileId } from './ruleProfile.js';

/** Opaque identifier for a match (room / game instance). */
export type MatchId = string;

/** Opaque identifier for a player within a match. */
export type PlayerId = string;

/**
 * Resource kind held by a player. Left abstract on purpose: the concrete
 * archipelago resource set (timber, ore, fish, ...) is an M1 ruleset
 * decision, not a core-skeleton concern.
 */
export type ResourceType = string;

/**
 * A match's lifecycle stage, including the per-turn FSM `S1.2.4` formalizes
 * on top of the original coarse `lobby`/`setup`/`main`/`finished` set. Once a
 * match exits `setup` (the snake-draft placement, S1.1.3), every turn cycles
 * `roll` -> `main`: `roll` is the turn's mandatory first step (only
 * `intent.rollDice` is legal there); resource production (S1.2.1) is an
 * automatic, zero-duration pass-through straight to `main` — there is no
 * persisted "produce" state to sit in, `reduce.ts`'s `dice.rolled` case lands
 * the phase on `main` directly, whether or not a paired `resources.produced`
 * event follows. `main` covers everything else (build/buy/play/endTurn);
 * `intent.endTurn` returns the NEXT player to `roll` (`reduce.ts`'s
 * `turn.ended` case). `robber` is a **documented seam only** — no code path
 * enters it yet; S1.3.1 owns wiring a rolled 7 (or a played knight) into it
 * for discard/robber-relocation. Until then a 7 falls straight through to
 * `main` like any other roll (`validate.ts`'s `rollDice` branch).
 */
export type GamePhase = 'lobby' | 'setup' | 'roll' | 'main' | 'robber' | 'finished';

/**
 * Classic development-card kind (S1.2.3, `devcards.ts`). `victoryPoint` is
 * never "played" via `intent.playDevCard` — it's bought and silently counts
 * toward the win threshold (E1.3 S1.3.4), so {@link PlayDevCardIntent}
 * excludes it by construction. `knight`'s effect (move robber + steal) is a
 * robber action deferred to S1.3.1 — see {@link PlayKnightIntent}.
 */
export type DevCardKind =
  'knight' | 'roadBuilding' | 'yearOfPlenty' | 'monopoly' | 'victoryPoint';

/**
 * A tile's resource kind, or `'desert'` (produces nothing, hosts the
 * robber's starting position). The concrete Classic set
 * (`timber/clay/fleece/barley/iron`) is generated by `boardgen.ts` (S1.1.2);
 * this alias just names the shape for `GameState`/events.
 */
export type TileKind = ResourceType | 'desert';

/**
 * One port's trade content: generic 3:1 with any resource, or a specific
 * resource's 2:1. Assigned onto the S1.1.1 `BoardTopology.portSlots` by
 * `boardgen.ts` (S1.1.2) — `PortContent[i]` pairs with `portSlots[i]`.
 */
export type PortContent =
  | { readonly kind: 'generic'; readonly rate: 3 }
  | { readonly kind: 'resource'; readonly rate: 2; readonly resource: ResourceType };

/**
 * A single player's public state. Plain data only (ADR-0003): `resources`
 * is a plain object, never a `Map`, so it serializes and deep-compares
 * deterministically.
 */
export interface PlayerState {
  readonly id: PlayerId;
  readonly name: string;
  readonly victoryPoints: number;
  readonly resources: Readonly<Record<ResourceType, number>>;
}

/**
 * The generated board layout (S1.1.2, `boardgen.ts`): tile kinds and number
 * tokens keyed by `TileId` (S1.1.1), port contents parallel to
 * `BoardTopology.portSlots`, and the robber's starting tile. Landed on
 * `GameState` by applying a `board.generated` event — never recomputed by
 * `reduce` itself (ADR-0003: the layout is a fact, not a recipe).
 */
export interface BoardState {
  readonly tileKinds: Readonly<Record<TileId, TileKind>>;
  /** Non-desert tiles only — a desert tile has no key here (not `undefined`). */
  readonly tileTokens: Readonly<Record<TileId, number>>;
  readonly portContents: readonly PortContent[];
  readonly robberTileId: TileId;
}

/**
 * Placed settlements/roads, keyed by board position (S1.1.3). Plain
 * `Record`s, not `Map`s (ADR-0003) — `settlements[vertexId]`/`roads[edgeId]`
 * is the owning player, or absent if that position is unbuilt.
 */
export interface BuildingsState {
  readonly settlements: Readonly<Record<VertexId, PlayerId>>;
  readonly roads: Readonly<Record<EdgeId, PlayerId>>;
  /**
   * Vertices upgraded from a settlement to a city (S1.2.2 `city.built`) —
   * absent until the first city lands, the same "fact of an event having
   * landed" optionality as the rest of `GameState` (ADR-0003). A city
   * vertex is removed from {@link settlements} when it moves here — a city
   * replaces its settlement, it never coexists with one at the same vertex.
   */
  readonly cities?: Readonly<Record<VertexId, PlayerId>>;
}

/**
 * One player's development-card holdings (S1.2.3). `held` counts by kind
 * (never individual card identities) — see {@link GameState.devCards} for
 * the privacy rationale. `boughtThisTurn` mirrors the same per-kind shape,
 * tracking how many of each kind were bought DURING the current turn (never
 * exceeding the matching `held` entry) — a card only becomes playable once
 * its `held` count exceeds its `boughtThisTurn` count (`validate.ts`'s
 * `intent.playDevCard` branch).
 */
export interface DevCardHoldings {
  readonly held: Readonly<Partial<Record<DevCardKind, number>>>;
  readonly boughtThisTurn: Readonly<Partial<Record<DevCardKind, number>>>;
}

/**
 * An open player↔player trade offer (S1.3.2) — at most one lives on
 * {@link GameState} at a time (M1 simplification: a second `proposeTrade`
 * while one is open is rejected with `TRADE_OFFER_ALREADY_OPEN`, forcing the
 * existing offer to resolve first). `give`/`get` are always from
 * {@link proposerId}'s perspective (`give` leaves the proposer, `get` arrives
 * at the proposer) — a `counterTrade` swaps roles by opening a NEW offer
 * with the countering player as {@link proposerId} and `give`/`get` from
 * THEIR perspective, `targets` narrowed to just the original proposer.
 * {@link depth} is the counter-offer bound: `0` for the original proposal,
 * `1` for its (at most one) counter — a `counterTrade` attempted at `depth
 * 1` is rejected with `TRADE_COUNTER_LIMIT_REACHED` (no infinite chains,
 * M1 spec: simple offer -> counter -> accept/reject only).
 */
export interface TradeOffer {
  readonly proposerId: PlayerId;
  readonly give: Readonly<Record<ResourceType, number>>;
  readonly get: Readonly<Record<ResourceType, number>>;
  readonly targets: readonly PlayerId[];
  readonly depth: number;
}

/**
 * The full authoritative game state. A plain, JSON-serializable object —
 * no class instances, no functions, no `Map`/`Set` — so it can be
 * event-sourced (replay = truth) and deep-compared byte-for-byte
 * (ADR-0003, `docs/wiki/deterministic-core.md`).
 */
export interface GameState {
  readonly matchId: MatchId;
  readonly phase: GamePhase;
  /** 1-based turn counter; advances on `turn.ended`. */
  readonly turn: number;
  readonly currentPlayerId: PlayerId;
  readonly players: ReadonlyArray<PlayerState>;
  /**
   * The fixed clockwise seating order (S1.2.4), set once by `match.started`
   * from `MatchStartedEvent.playerIds` (`reduce.ts`) and never reordered
   * afterward — unlike {@link GameState.currentPlayerId}, which rotates every
   * `turn.ended`. Both the setup snake-draft's exit transition
   * (`road.placed`'s `nextPlayerId`, S1.1.3) and the main loop's `endTurn`
   * rotation read this ONE array (`validate.ts`'s `seatOrder` helper) instead
   * of each re-deriving "next player" from {@link GameState.players}'
   * incidental array order — the implicit coupling S1.1.3's review flagged.
   * Absent before `match.started` lands, the same "fact of an event having
   * landed" optionality as {@link GameState.board} — `seatOrder` falls back
   * to `players`' own order for a state assembled without that event
   * (pre-S1.2.4 test fixtures), a defensive fallback only: once
   * `playerOrder` IS set, every rotation reads it exclusively.
   */
  readonly playerOrder?: ReadonlyArray<PlayerId>;
  /**
   * Count of events applied so far. Doubles as the PRNG stream index
   * (`docs/wiki/fair-rng-commit-reveal.md`): randomness is derived from
   * `seed` + this index, never drawn ambiently.
   */
  readonly eventIndex: number;
  /** `SHA256(seed)`, published before the match (commit step of commit-reveal). */
  readonly seedHash: string;
  /**
   * The rule profile in force for this match (S2.1.1), fixed once by
   * `match.started` from {@link MatchStartedEvent.profileId} and never changed.
   * The engine resolves it to a full {@link RuleProfile} via `loadRuleProfile`
   * (`ruleProfile.ts`) at each rule-knob read, so a match's rules are a fact
   * carried in the log — replay and the S1.7.3 verifier resolve identical
   * rules (event-sourcing). Optional (like {@link GameState.board}) so states
   * assembled without a `match.started` carrying it — pre-S2.1.1 golden
   * fixtures and unit-test genesis literals — stay byte-identical; a missing
   * `profileId` resolves to `'classic'`, the M1 default.
   */
  readonly profileId?: RuleProfileId;
  /**
   * Present once `board.generated` has been applied (S1.1.2), absent
   * before — optional rather than a placeholder value so pre-S1.1.2 golden
   * fixtures (no board event in their log) stay byte-identical unchanged.
   */
  readonly board?: BoardState;
  /**
   * Present once the first `settlement.placed` has been applied (S1.1.3),
   * absent before — same "fact of an event having landed" optionality as
   * {@link GameState.board}, so fixtures that never reach the setup
   * placement flow stay byte-identical.
   */
  readonly buildings?: BuildingsState;
  /**
   * The vertex of the settlement placed earlier THIS draft turn, awaiting
   * its attached road (S1.1.3 snake draft) — absent when no settlement is
   * pending (either between draft turns, or outside setup entirely). Set by
   * `settlement.placed`, cleared by `road.placed`.
   */
  readonly pendingRoadVertexId?: VertexId;
  /**
   * The finite bank's remaining pool, per resource (S1.2.1 production/bank-
   * exhaustion rule). Absent until the first `resources.produced` event
   * touches a resource — same "fact of an event having landed" optionality
   * as {@link GameState.board}; a resource with no key here still has its
   * full Classic pool (`CLASSIC_PRODUCTION_PROFILE.bankPerResource`,
   * `validate.ts`), it just hasn't been drawn from yet.
   */
  readonly bank?: Readonly<Record<ResourceType, number>>;
  /**
   * The Classic dev-card deck's remaining undrawn count (S1.2.3) — absent
   * means "no `devCard.bought` event has landed yet" (full count is
   * `CLASSIC_DEV_CARD_PROFILE.deck.length`, 25, `devcards.ts`), the same
   * optionality pattern as {@link GameState.bank}. The deck's concrete
   * shuffled ORDER never lives on state — only `devcards.ts`'s
   * `shuffledDevDeck(seed)` can recompute it, and only `validate.ts`'s buy
   * branch ever calls that. Storing the order here would let a serialized
   * state snapshot predict every future draw before it happens — the same
   * reasoning that keeps the raw `seed` itself out of `GameState`
   * (`docs/wiki/fair-rng-commit-reveal.md`).
   */
  readonly devDeckRemaining?: number;
  /**
   * Per-player development-card holdings (S1.2.3), keyed by `PlayerId` —
   * absent until the first `devCard.bought` lands, same "fact of an event
   * having landed" optionality as {@link GameState.buildings}. Each
   * holding's `held` is a per-kind COUNT, not a list of individual card
   * identities, so a future per-viewer redaction (server concern, not yet
   * built) only needs to sum another player's `held` values into a single
   * total — this player's own client still gets the full per-kind
   * breakdown, exactly like {@link PlayerState.resources} already does
   * today. Reset per player to `{ held, boughtThisTurn: {} }` on
   * `turn.ended` (`reduce.ts`) — `held` itself is untouched by a turn
   * ending.
   */
  readonly devCards?: Readonly<Record<PlayerId, DevCardHoldings>>;
  /**
   * True once the current player has played a development card THIS turn
   * (Classic: one per turn) — absent between turns, set by any
   * `devCard.*Played` event, cleared on `turn.ended`. A minimal reset
   * landed here so S1.2.3's own tests can exercise a second turn; S1.2.4
   * owns formalizing the full per-turn-marker reset architecture.
   */
  readonly devCardPlayedThisTurn?: boolean;
  /**
   * Present only while `phase === 'robber'` and at least one player still
   * owes a post-7 discard (S1.3.1) — the list of {@link PlayerId}s who must
   * `intent.discard` before the mover may `intent.moveRobber`. Dropped
   * entirely (not set to an empty array) once the last owing player
   * discards, or was never set at all for a knight-triggered robber move
   * (Classic: no discard step) — same "absent key = condition resolved /
   * never applied" optionality as {@link GameState.pendingRoadVertexId}.
   */
  readonly playersToDiscard?: readonly PlayerId[];
  /**
   * Per-player count of knights played (S1.3.1), keyed by `PlayerId` —
   * absent until the first `devCard.knightPlayed` lands, same "fact of an
   * event having landed" optionality as {@link GameState.devCards}. Never
   * reset by `turn.ended` (a match-long running total, unlike the per-turn
   * markers) — feeds the largest-army calculation (S1.3.4).
   */
  readonly knightsPlayed?: Readonly<Record<PlayerId, number>>;
  /**
   * The current holder of the **longest road** award (S1.3.4), or absent
   * when no player holds it (nobody's longest simple road path reaches the
   * Classic minimum of 5, or a break left the lead tied — see
   * `validate.ts`'s `computeLongestRoad`). Set/cleared by
   * {@link LongestRoadAwardedEvent}; worth +2 toward the win threshold while
   * held. Absent until the first award lands, the same "fact of an event
   * having landed" optionality as {@link GameState.knightsPlayed}.
   */
  readonly longestRoadHolder?: PlayerId;
  /**
   * The current holder of the **largest army** award (S1.3.4), or absent
   * when no player has yet played the Classic minimum of 3 knights. Set by
   * {@link LargestArmyAwardedEvent}; worth +2 toward the win threshold.
   * Unlike {@link GameState.longestRoadHolder} it never vacates once earned
   * — a played knight can only be gained, so the count never falls; the
   * award only ever transfers to a player with a STRICTLY higher count
   * (`validate.ts`'s `computeLargestArmy`).
   */
  readonly largestArmyHolder?: PlayerId;
  /**
   * The currently open trade offer (S1.3.2), if any — absent means no
   * `proposeTrade`/`counterTrade` is pending, same "fact of an event having
   * landed" optionality as {@link GameState.pendingRoadVertexId}. Dropped by
   * `trade.executed` (accepted), `trade.rejected` (once every target has
   * rejected — see {@link TradeOffer.targets} shrinking), `trade.cancelled`
   * (by the offer's own proposer), and implicitly by `turn.ended` (an open
   * offer never survives past the turn it was made in, `reduce.ts`'s
   * per-turn-marker reset).
   */
  readonly openTradeOffer?: TradeOffer;
}

/** Fields shared by every {@link GameEvent} variant. */
interface BaseGameEvent {
  /** Position of this event in the match's event log / PRNG stream. */
  readonly index: number;
}

/** Emitted once when a match's authoritative state is initialized. */
export interface MatchStartedEvent extends BaseGameEvent {
  readonly type: 'match.started';
  readonly matchId: MatchId;
  readonly seedHash: string;
  readonly playerIds: ReadonlyArray<PlayerId>;
  /**
   * The rule profile selected for this match (S2.1.1). Append-compatible and
   * optional: an event without it (pre-S2.1.1 golden fixtures) folds to a
   * `GameState` whose `profileId` stays absent and resolves to `'classic'`.
   * `GameRoom` always emits `'classic'` for now (mode selection UI = S2.5.4).
   */
  readonly profileId?: RuleProfileId;
}

/**
 * Emitted once during setup when the Classic board layout is generated from
 * the match seed (S1.1.2, `boardgen.ts`). Carries the FULL layout — tile
 * kinds/tokens, port contents, robber start — so replay never re-runs the
 * generator; the layout is a fact, like every other event (ADR-0003).
 */
export interface BoardGeneratedEvent extends BaseGameEvent {
  readonly type: 'board.generated';
  readonly tileKinds: Readonly<Record<TileId, TileKind>>;
  readonly tileTokens: Readonly<Record<TileId, number>>;
  readonly portContents: readonly PortContent[];
  readonly robberTileId: TileId;
}

/**
 * A dice roll resolved by the server from the seeded PRNG (S1.2.1: Classic
 * play is always 2d6, not 1 die — `dieA`/`dieB`/`total` are facts, never
 * generated inside `reduce` itself, only carried as event data, ADR-0003).
 * Recording both faces (not just `total`) means replay never needs to
 * re-derive them from the seed — see `docs/wiki/rng-stream-map.md`.
 */
export interface DiceRolledEvent extends BaseGameEvent {
  readonly type: 'dice.rolled';
  readonly playerId: PlayerId;
  readonly dieA: number;
  readonly dieB: number;
  readonly total: number;
  /**
   * Present ONLY when `total === 7` (S1.3.1): the players who must discard
   * down to `floor(handSize / 2)` before the robber can move — a fact
   * `validate` already computed from hand sizes, so `reduce`/replay never
   * recompute it. An EMPTY array is itself a recorded fact ("a 7 landed, but
   * nobody happened to be holding more than 7 cards") — same "still emitted
   * so absence isn't inferred" discipline as {@link ResourcesProducedEvent.grants}.
   * Absence of the field entirely means this roll wasn't a 7 at all.
   */
  readonly playersToDiscard?: readonly PlayerId[];
}

/**
 * Resource production resolved from a roll (S1.2.1 Classic spec): `grants`
 * is the explicit per-player payout (keyed by `PlayerId`, then
 * `ResourceType`) and `bank` is the FULL resultant bank pool after this
 * roll — both are facts `validate` computes once so `reduce`/replay never
 * recompute the bank-exhaustion math (ADR-0003). Emitted alongside
 * `dice.rolled` for every roll except a 7 (robber — deferred to S1.3.1,
 * see the `validate.ts` `rollDice` branch); `grants` is `{}` when nothing
 * produces (e.g. no board yet, no tile matches, or bank exhaustion voided
 * every entitled resource this roll) — still emitted so "this roll produced
 * nothing" is itself a recorded fact, not an absence to infer.
 */
export interface ResourcesProducedEvent extends BaseGameEvent {
  readonly type: 'resources.produced';
  readonly grants: Readonly<Record<PlayerId, Readonly<Record<ResourceType, number>>>>;
  readonly bank: Readonly<Record<ResourceType, number>>;
}

/** Emitted when a player's turn ends and play passes to the next player. */
export interface TurnEndedEvent extends BaseGameEvent {
  readonly type: 'turn.ended';
  readonly playerId: PlayerId;
  readonly nextPlayerId: PlayerId;
}

/**
 * Emitted when a player places a settlement during the snake-draft setup
 * phase (S1.1.3). `payout` is the second-settlement resource grant (tech
 * spec: 1 resource per adjacent producing tile, desert pays nothing) —
 * `validate` computes it once from `GameState.board`, and it travels here as
 * an explicit fact so `reduce`/replay never recompute it (ADR-0003). Empty
 * for a player's first settlement.
 */
export interface SettlementPlacedEvent extends BaseGameEvent {
  readonly type: 'settlement.placed';
  readonly playerId: PlayerId;
  readonly vertexId: VertexId;
  readonly payout: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a player places the road attached to the settlement they
 * just placed, completing one snake-draft turn (S1.1.3). `nextPlayerId`/
 * `nextPhase` are the snake-order/setup-completion facts `validate` already
 * worked out — `reduce` only applies them, never re-derives draft order
 * (ADR-0003: events are facts, not recipes).
 */
export interface RoadPlacedEvent extends BaseGameEvent {
  readonly type: 'road.placed';
  readonly playerId: PlayerId;
  readonly edgeId: EdgeId;
  readonly nextPlayerId: PlayerId;
  readonly nextPhase: GamePhase;
}

/**
 * Emitted when a player builds a road during the main phase (S1.2.2,
 * distinct from the free {@link RoadPlacedEvent} of the setup draft — this
 * one costs resources). `cost` is the debit `validate` already computed
 * (affordability was checked before emitting) — an explicit fact, so
 * `reduce` only subtracts, never re-derives the Classic price list
 * (ADR-0003).
 */
export interface RoadBuiltEvent extends BaseGameEvent {
  readonly type: 'road.built';
  readonly playerId: PlayerId;
  readonly edgeId: EdgeId;
  readonly cost: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a player builds a settlement during the main phase (S1.2.2,
 * distinct from the free {@link SettlementPlacedEvent} of the setup draft —
 * this one costs resources and requires an own road connection). `cost` is
 * the debit `validate` already computed, the same explicit-fact discipline
 * as {@link RoadBuiltEvent}.
 */
export interface SettlementBuiltEvent extends BaseGameEvent {
  readonly type: 'settlement.built';
  readonly playerId: PlayerId;
  readonly vertexId: VertexId;
  readonly cost: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a player upgrades their own settlement into a city (S1.2.2).
 * `reduce` moves `vertexId` from {@link BuildingsState.settlements} to
 * {@link BuildingsState.cities} and debits `cost` — both mechanical facts
 * this event already carries, per the same discipline as every other build
 * event.
 */
export interface CityBuiltEvent extends BaseGameEvent {
  readonly type: 'city.built';
  readonly playerId: PlayerId;
  readonly vertexId: VertexId;
  readonly cost: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a player buys a development card (S1.2.3): draws the top of
 * the seed-shuffled deck (`devcards.ts`'s `shuffledDevDeck`, indexed at the
 * count already drawn so far — the same "recompute from seed, never store
 * the order" discipline as dice rolls, see {@link GameState.devDeckRemaining}).
 * `card` is the drawn identity (a fact, like {@link DiceRolledEvent}'s
 * faces); `cost` is the debit `validate` already computed; `deckRemaining`
 * is the count AFTER this draw.
 */
export interface DevCardBoughtEvent extends BaseGameEvent {
  readonly type: 'devCard.bought';
  readonly playerId: PlayerId;
  readonly card: DevCardKind;
  readonly cost: Readonly<Record<ResourceType, number>>;
  readonly deckRemaining: number;
}

/**
 * Emitted when a player plays a road-building card (S1.2.3): up to 2 free
 * roads, reusing the S1.2.2 road-legality rules (`validate.ts`'s
 * `touchesOwnNetwork`). `edgeIds` is 0, 1, or 2 entries — fewer than 2 only
 * when no further legal edge existed or the player's road supply was
 * exhausted mid-play (Classic spec: the card is still consumed either way).
 */
export interface RoadBuildingPlayedEvent extends BaseGameEvent {
  readonly type: 'devCard.roadBuildingPlayed';
  readonly playerId: PlayerId;
  readonly edgeIds: readonly EdgeId[];
}

/**
 * Emitted when a player plays a year-of-plenty card (S1.2.3): `resources`
 * is the explicit 2-card grant `validate` already checked against bank
 * stock (may name the same resource twice); `bank` is the full resultant
 * pool after, the same explicit-fact discipline as {@link
 * ResourcesProducedEvent}.
 */
export interface YearOfPlentyPlayedEvent extends BaseGameEvent {
  readonly type: 'devCard.yearOfPlentyPlayed';
  readonly playerId: PlayerId;
  readonly resources: Readonly<Record<ResourceType, number>>;
  readonly bank: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a player plays a monopoly card (S1.2.3): `resource` is the
 * named resource, `transfers` is the EXPLICIT per-victim amount `validate`
 * already read off each other player's holdings at play time (a fact, not
 * a recipe — `reduce` only moves the amounts, never re-derives them).
 * Players owning 0 of `resource` are simply absent from `transfers`.
 */
export interface MonopolyPlayedEvent extends BaseGameEvent {
  readonly type: 'devCard.monopolyPlayed';
  readonly playerId: PlayerId;
  readonly resource: ResourceType;
  readonly transfers: Readonly<Record<PlayerId, number>>;
}

/**
 * Emitted when an owing player discards half their hand after a 7 (S1.3.1
 * spec: every player holding >7 resource cards discards `floor(handSize /
 * 2)`, their OWN choice of which cards). `resources` is the exact discarded
 * multiset (an explicit fact, not a count — `reduce` only subtracts, never
 * re-derives it); `remainingToDiscard` is `GameState.playersToDiscard`
 * AFTER this discard resolves (`validate` already recomputed the list once,
 * the same "fact, not a recipe" discipline as {@link RoadPlacedEvent.nextPlayerId}) —
 * an empty array means every owing player has now discarded and the mover
 * may relocate the robber.
 */
export interface ResourcesDiscardedEvent extends BaseGameEvent {
  readonly type: 'resources.discarded';
  readonly playerId: PlayerId;
  readonly resources: Readonly<Record<ResourceType, number>>;
  readonly remainingToDiscard: readonly PlayerId[];
}

/**
 * Emitted when the robber relocates and (maybe) steals — the shared
 * resolution both a 7-roll (via `intent.moveRobber`, after any discards
 * clear) and a played knight (paired right after {@link KnightPlayedEvent})
 * land through (S1.3.1 spec). `stolenFrom`/`stolenResource` are BOTH present
 * or BOTH absent: present when the mover named a victim who had ≥1 card (the
 * resource is the PRNG's pick, a fact `validate` already drew — replay never
 * re-draws it); absent when no adjacent victim held any cards (a documented
 * no-op steal). `nextPhase` is the phase the turn resumes in: always `'main'`
 * for the 7-roll path (rolling — 7 or not — already consumed the turn's
 * roll), or whatever phase the knight was played FROM (`'roll'` pre-roll,
 * `'main'` post-roll, Classic allows either) for the knight path — an
 * explicit fact so `reduce` never has to remember which path produced this
 * event.
 */
export interface RobberMovedEvent extends BaseGameEvent {
  readonly type: 'robber.moved';
  readonly playerId: PlayerId;
  readonly tileId: TileId;
  readonly stolenFrom?: PlayerId;
  readonly stolenResource?: ResourceType;
  readonly nextPhase: GamePhase;
}

/**
 * Emitted when a player plays a knight (S1.3.1, un-deferred from S1.2.3's
 * `KNIGHT_DEFERRED`): consumes the held card and marks the per-turn played
 * marker exactly like every other dev-card play, and additionally bumps the
 * player's played-knight count (largest army, S1.3.4). Always immediately
 * followed by a {@link RobberMovedEvent} carrying the actual relocate+steal
 * (`validate`'s `playDevCard` knight branch emits both events together,
 * mirroring {@link DiceRolledEvent}/{@link ResourcesProducedEvent}'s
 * roll+production pairing) — this event alone only enters the `'robber'`
 * phase seam, the same "zero-duration pass-through" shape `dice.rolled` uses
 * for production.
 */
export interface KnightPlayedEvent extends BaseGameEvent {
  readonly type: 'devCard.knightPlayed';
  readonly playerId: PlayerId;
}

/**
 * Emitted when a `proposeTrade` or `counterTrade` intent opens a new offer
 * (S1.3.2) — both land through this SAME event type (a counter is just a
 * new offer with swapped `proposerId`/`give`/`get`/narrowed `targets` and
 * `depth + 1`, see {@link TradeOffer}); `reduce` only ever needs one case to
 * set {@link GameState.openTradeOffer}. Replaces (not merges with) any
 * offer the acting player's own prior proposal already closed — only one
 * offer is ever open at a time (`validate`'s `TRADE_OFFER_ALREADY_OPEN`
 * guard on a fresh `proposeTrade`).
 */
export interface TradeOfferedEvent extends BaseGameEvent {
  readonly type: 'trade.offered';
  readonly proposerId: PlayerId;
  readonly give: Readonly<Record<ResourceType, number>>;
  readonly get: Readonly<Record<ResourceType, number>>;
  readonly targets: readonly PlayerId[];
  readonly depth: number;
}

/**
 * Emitted when a targeted player accepts the open offer (S1.3.2) — the
 * ATOMIC swap: both concrete bundles + both party ids travel on this ONE
 * event, so `reduce` debits+credits both sides in a single state
 * transition. There is no intermediate state where one side has paid and
 * the other hasn't — `give`/`get` keep {@link GameState.openTradeOffer}'s
 * own proposer-perspective naming (`give` leaves the proposer and arrives
 * at the accepter; `get` is the reverse), never re-derived by `reduce`
 * (ADR-0003: events are facts, not recipes).
 */
export interface TradeExecutedEvent extends BaseGameEvent {
  readonly type: 'trade.executed';
  readonly proposerId: PlayerId;
  readonly accepterId: PlayerId;
  readonly give: Readonly<Record<ResourceType, number>>;
  readonly get: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when a targeted player rejects the open offer (S1.3.2).
 * `remainingTargets` is `GameState.openTradeOffer.targets` AFTER this
 * rejection (a fact `validate` already recomputed once, the same discipline
 * as {@link ResourcesDiscardedEvent.remainingToDiscard}) — an empty array
 * means every target has now rejected, so `reduce` closes the offer
 * entirely; a non-empty array leaves it open for the remaining targets.
 */
export interface TradeRejectedEvent extends BaseGameEvent {
  readonly type: 'trade.rejected';
  readonly playerId: PlayerId;
  readonly remainingTargets: readonly PlayerId[];
}

/**
 * Emitted when the open offer's own proposer withdraws it (S1.3.2) — legal
 * for whoever proposed the CURRENTLY open offer, which after a
 * `counterTrade` is the countering player, not necessarily
 * `GameState.currentPlayerId` (`validate`'s `NOT_TRADE_PROPOSER` guard).
 */
export interface TradeCancelledEvent extends BaseGameEvent {
  readonly type: 'trade.cancelled';
  readonly playerId: PlayerId;
}

/**
 * Emitted when a player trades with the bank at their resolved rate
 * (S1.3.3): `count` of `give` leaves the player for exactly 1 unit of
 * `get` — `count` is the RATE `validate` already resolved from the
 * player's owned ports (best of 2:1/3:1/4:1, `validate.ts`'s
 * `bestBankRate`), an explicit fact so `reduce` never re-derives port
 * ownership. `bank` is the FULL resultant pool after the trade (both the
 * `get` debit and the `give` credit), the same explicit-fact discipline as
 * {@link ResourcesProducedEvent}/{@link YearOfPlentyPlayedEvent}.
 */
export interface BankTradedEvent extends BaseGameEvent {
  readonly type: 'bank.trade';
  readonly playerId: PlayerId;
  readonly give: ResourceType;
  readonly count: number;
  readonly get: ResourceType;
  readonly bank: Readonly<Record<ResourceType, number>>;
}

/**
 * Emitted when the **longest road** award changes hands (S1.3.4) — the
 * derived-fact counterpart of a build that reshaped the road graph
 * (`road.built`, `devCard.roadBuildingPlayed`) or an opponent settlement
 * that broke a road (`settlement.built`/`city.built`). `validate` recomputes
 * every player's longest simple road path from the post-build state and
 * emits this ONLY when the holder actually changes, so replay applies the
 * fact rather than re-running the graph search (ADR-0003). `playerId` is the
 * NEW holder; it is ABSENT when the award VACATES (no player ≥ the Classic
 * minimum, or the lead is tied with no incumbent to keep it). `length` is the
 * winning path length (the vacating event still carries the best remaining
 * length as an audit fact).
 */
export interface LongestRoadAwardedEvent extends BaseGameEvent {
  readonly type: 'award.longestRoad';
  readonly playerId?: PlayerId;
  readonly length: number;
}

/**
 * Emitted when the **largest army** award changes hands (S1.3.4) — always
 * paired right after the {@link KnightPlayedEvent}/{@link RobberMovedEvent}
 * that bumped the actor's played-knight count past the incumbent's. Unlike
 * {@link LongestRoadAwardedEvent} this never vacates (knight counts only
 * rise, and the award only moves to a STRICTLY higher count), so `playerId`
 * is always present. `knights` is the new holder's played-knight count.
 */
export interface LargestArmyAwardedEvent extends BaseGameEvent {
  readonly type: 'award.largestArmy';
  readonly playerId: PlayerId;
  readonly knights: number;
}

/**
 * Emitted when the acting player reaches the Classic victory threshold
 * (`vpToWin`, 10) on THEIR OWN turn (S1.3.4) — the full tally includes
 * hidden VP dev cards, which is why the win is only ever checked for the
 * player currently acting (an opponent pushed to the threshold by someone
 * else's turn does NOT win). `validate` appends this after the triggering
 * action's events (and any award change it caused); `reduce` moves the phase
 * to `'finished'` and every later gameplay intent is then rejected with
 * `GAME_ALREADY_ENDED`. `finalStandings` is the full VP tally per player at
 * match end (an audit fact, so replay never recomputes it).
 */
export interface GameEndedEvent extends BaseGameEvent {
  readonly type: 'game.ended';
  readonly winnerId: PlayerId;
  readonly finalStandings: Readonly<Record<PlayerId, number>>;
}

/**
 * A fact that mutates {@link GameState} via `reduce`. Discriminated by
 * `type`. Only events change state — intents never do directly
 * (ADR-0003). M1 Classic rules keep extending this set (build lands here,
 * S1.2.2; dev cards, S1.2.3; robber/7 + knight, S1.3.1; trade, S1.3.2; bank
 * trade, S1.3.3; awards + victory, S1.3.4).
 */
export type GameEvent =
  | MatchStartedEvent
  | BoardGeneratedEvent
  | DiceRolledEvent
  | ResourcesProducedEvent
  | TurnEndedEvent
  | SettlementPlacedEvent
  | RoadPlacedEvent
  | RoadBuiltEvent
  | SettlementBuiltEvent
  | CityBuiltEvent
  | DevCardBoughtEvent
  | RoadBuildingPlayedEvent
  | YearOfPlentyPlayedEvent
  | MonopolyPlayedEvent
  | ResourcesDiscardedEvent
  | RobberMovedEvent
  | KnightPlayedEvent
  | TradeOfferedEvent
  | TradeExecutedEvent
  | TradeRejectedEvent
  | TradeCancelledEvent
  | BankTradedEvent
  | LongestRoadAwardedEvent
  | LargestArmyAwardedEvent
  | GameEndedEvent;

